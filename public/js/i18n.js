// ── Language Detection & Switching ──
const SUPPORTED_LANGS = ['en', 'nl', 'ar', 'tr', 'pl', 'zh'];
const LANG_NAMES = {
  en: 'English',
  nl: 'Nederlands',
  ar: 'العربية',
  tr: 'Türkçe',
  pl: 'Polski',
  zh: '中文'
};

// Detect language from browser or URL or localStorage
function detectLanguage() {
  // 1. URL param
  const params = new URLSearchParams(window.location.search);
  if (params.get('lang') && SUPPORTED_LANGS.includes(params.get('lang'))) {
    return params.get('lang');
  }
  // 2. localStorage
  const saved = localStorage.getItem('recipeBookLang');
  if (saved && SUPPORTED_LANGS.includes(saved)) return saved;
  // 3. Browser language
  const browserLang = navigator.language.split('-')[0];
  if (SUPPORTED_LANGS.includes(browserLang)) return browserLang;
  // 4. Default
  return 'en';
}

function setLanguage(lang) {
  if (!SUPPORTED_LANGS.includes(lang)) lang = 'en';
  localStorage.setItem('recipeBookLang', lang);
  // For Arabic: set dir=rtl on body
  document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
  document.documentElement.lang = lang;
  applyTranslations(lang);
}

function applyTranslations(lang) {
  const t = translations[lang];
  if (!t) return;

  // Translate all elements with data-i18n attribute
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (t[key] !== undefined) {
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        el.placeholder = t[key];
      } else {
        el.innerHTML = t[key];
      }
    }
  });

  // Translate page title
  if (t.heroTitle) document.title = t.heroTitle + ' — 🥟';

  // Update language selector
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.lang === lang);
  });
}

// ── Export for use in other scripts ──
window.i18n = { translations, SUPPORTED_LANGS, LANG_NAMES, detectLanguage, setLanguage, applyTranslations };